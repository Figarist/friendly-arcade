#!/usr/bin/env node
// Builds friendly-arcade.css (single-file bundle) from the hand-written layers.
// Usage: node scripts/build.mjs [--check]
// --check writes nothing and exits 1 when the bundle is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCES = ['tokens.css', 'base.css', 'components.css'];
export const BUNDLE = 'friendly-arcade.css';

const read = (rel) => readFileSync(join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
const version = JSON.parse(read('package.json')).version;

/** Returns Map(name -> value) of custom properties in the first block matching `selector` in tokens.css. */
export function parseTokens(selector = ':root', css = read('tokens.css')) {
  const esc = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const block = css.match(new RegExp(`(^|\\n)${esc}\\s*\\{([\\s\\S]*?)\\n\\}`));
  if (!block) throw new Error(`tokens.css has no ${selector} block`);
  const body = block[2].replace(/\/\*[\s\S]*?\*\//g, '');
  return new Map([...body.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}

export function buildBundle() {
  const banner = `/*! Friendly Arcade UI v${version} | MIT | https://github.com/Figarist/friendly-arcade */\n` +
    `/* Generated by scripts/build.mjs from ${SOURCES.join(', ')}. Do not edit; change the layers instead. */\n`;
  return banner + SOURCES.map((f) => `\n/* ---- ${f} ---- */\n` + read(f).trim() + '\n').join('');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = buildBundle();
  let current = null;
  try { current = read(BUNDLE); } catch { /* missing */ }
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error(`stale: ${BUNDLE} (run npm run build)`);
      process.exit(1);
    }
    console.log(`${BUNDLE} is up to date`);
  } else if (current !== next) {
    writeFileSync(join(ROOT, BUNDLE), next);
    console.log(`wrote ${BUNDLE}`);
  }
}
